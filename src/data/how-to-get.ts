export function ridesForZone(zone: string) {
  return rideOptions.filter((item) => item.zone === zone);
}

export type DecoratedRide = RideOption & {
  isCheapest: boolean;
  isFastest: boolean;
  isGreenest: boolean;
  isDirect: boolean;
};

export function decorateRides(list: RideOption[]): DecoratedRide[] {
  if (!list.length) return [];
  const cheapest = Math.min(...list.map((item) => item.usdMin));
  const fastest = Math.min(...list.map((item) => item.hours));
  const greenest = Math.min(...list.map((item) => item.co2kg));
  return list.map((item) => ({
    ...item,
    isCheapest: item.usdMin === cheapest,
    isFastest: item.hours === fastest,
    isGreenest: item.co2kg === greenest,
    isDirect: item.connections === 0 && item.hops.length === 1,
  }));
}
